package com.ganeshfest.collection.enums;

/**
 * FESTIVAL      - one of the actual 3/5 pooja days of the utsav.
 * PRE_FESTIVAL  - a collection/prep day before the festival starts (people usually
 *                 start collecting chanda 10-15 days before Chaturthi, and early
 *                 expenses like booking the mandap/murti/tent need to be paid then too).
 */
public enum DayType {
    FESTIVAL, PRE_FESTIVAL
}
